# selftest
# ---------------------------------------------------------------------------
def _two_col(start=3.0, step=0.02, n=11, crlf=False):
    nl = '\r\n' if crlf else '\n'
    rows = ['%.3f %.0f' % (start + i * step, 100 + i) for i in range(n)]
    return (nl.join(rows) + nl).encode('utf-8')


def _scratch_root():
    """A directory the self test may write in, tried in order.

    tempfile.gettempdir() comes first, then the CWD and a subdirectory of it.
    Two findings are baked into this function, both measured on this host:

      * mkdtemp(str) is NOT used any more. Under the DSH sandbox the TEMP path
        is a redirected directory where `tempfile.mkdtemp()` succeeds but
        creating a FILE inside the directory it returns is refused outright
        (PermissionError), and the same happened for every mkdtemp directory
        under the workspace while `os.mkdir` / `os.makedirs` were perfectly
        writable. So directories are made by hand with a pid+counter suffix.
      * "I could create a directory" is not "I can write a file there", which
        is why each candidate is probed by writing and deleting a real file.
        A candidate that fails both is skipped; ./probe.tmp is the last resort
        because the workspace root itself is generally writable.
    """
    cands = []
    try:
        cands.append(tempfile.gettempdir())
    except Exception:
        pass
    cwd = os.getcwd()
    cands.extend([cwd, os.path.join(cwd, '_dat_align_selftest')])
    stale = []
    counter = [0]

    def make(base):
        # fresh directory under base (make base if needed), never mkdtemp
        if not os.path.isdir(base):
            os.makedirs(base)
        counter[0] += 1
        d = os.path.join(base, 'dat_align_%d_%d' % (os.getpid(), counter[0]))
        os.makedirs(d, exist_ok=True)
        stale.append(d)
        return d

    def writable(path):
        probe = os.path.join(path, 'probe.tmp')
        with open(probe, 'wb') as fh:
            fh.write(b'probe')
        os.remove(probe)

    for base in cands:
        try:
            d = make(base)
            writable(d)
            return d
        except Exception:
            continue
    try:                                   # last resort: the CWD itself
        writable(cwd)
        stale.append(None)
        return cwd
    except Exception:
        pass
    for d in stale:
        if d:
            shutil.rmtree(d, ignore_errors=True)
    raise DatAlignError('selftest: no writable scratch directory found')


def selftest():
    results = []
    root = _scratch_root()
    # Every directory this run creates is tracked and removed in the finally
    # block below; None means "root is the CWD itself, create nothing".
    scratch_dirs = [root] if root != os.getcwd() else []
    counter = [0]

    def newdir(tag):
        counter[0] += 1
        d = os.path.join(root, '%s_%d' % (tag, counter[0]))
        os.makedirs(d, exist_ok=True)
        scratch_dirs.append(d)
        return d

    def case(name, fn):
        try:
            detail = fn() or ''
            results.append((True, name, detail))
        except Exception as e:
            results.append((False, name, '%s: %s' % (type(e).__name__, e)))

    def expect(cond, msg):
        if not cond:
            raise AssertionError(msg)

    def exit_code(fn):
        """Run fn, return (code, message) the CLI would exit with.

        DatAlignError is caught as well as SystemExit because the library
        functions raise the former and main() turns it into the latter; testing
        only SystemExit would make every rejection look like a silent success.
        """
        try:
            fn()
        except SystemExit as e:
            return (e.code if e.code is not None else 0), str(e)
        except DatAlignError as e:
            return e.code, str(e)
        return 0, ''

    def case1():
        # no header at all: 6 lines padded, points = every data row
        tmp = newdir('st1')
        try:
            src = os.path.join(tmp, 'bare2c.dat')
            out = os.path.join(tmp, 'bare2c_aligned.dat')
            open(src, 'wb').write(_two_col(n=11))
            rep = run_make(src, out)
            expect(rep['added_lines'] == 6, 'added_lines=%r, want 6' % rep['added_lines'])
            expect(rep['leading_non_numeric'] == 0,
                   'leading=%r, want 0' % rep['leading_non_numeric'])
            expect(rep['blank_lines'] == 0, 'blank_lines=%r' % rep['blank_lines'])
            expect(rep['points'] == 11, 'points=%r, want 11' % rep['points'])
            expect(rep['columns'] == 2, 'columns=%r, want 2' % rep['columns'])
            expect(abs(rep['two_theta_min'] - 3.0) < 1e-9, '2theta_min=%r' % rep['two_theta_min'])
            expect(abs(rep['step'] - 0.02) < 1e-9, 'step=%r' % rep['step'])
            expect(abs(rep['two_theta_max'] - 3.2) < 1e-9, '2theta_max=%r' % rep['two_theta_max'])
            txt = open(out, 'rb').read().decode('utf-8')
            head = txt.split('\n')[:6]
            expect(head[0].startswith('COMM  '), 'line1=%r' % head[0])
            expect('source bare2c.dat sha256 ' in head[1], 'line2=%r' % head[1])
            expect(head[2:6] == ['COMM  -'] * 4, 'tail of header=%r' % head[2:6])
            expect(rep['src_sha256'] != rep['out_sha256'], 'hashes must differ')
            chk = run_check(out)
            expect(chk['ins10_ok'], 'check says not Ins=10 ready')
            expect(chk['leading_non_numeric'] == 6, 'check leading=%r' % chk['leading_non_numeric'])
            expect(chk['points_after_ins10'] == 11,
                   'points_after_ins10=%r, want 11 (no data may be lost)'
                   % chk['points_after_ins10'])
            return 'added 6, 11 points kept, check after Ins=10 = 11 points'
        finally:
            pass

    def case2():
        # already has 6 header lines: added 0, byte-identical copy
        tmp = newdir('st2')
        try:
            src = os.path.join(tmp, 'hdr6.dat')
            out = os.path.join(tmp, 'hdr6_aligned.dat')
            head = ('%s\n' % ('# vendor header, six lines')) * 6
            open(src, 'wb').write(head.encode('utf-8') + _two_col(n=9))
            rep = run_make(src, out)
            expect(rep['added_lines'] == 0, 'added_lines=%r, want 0' % rep['added_lines'])
            expect(rep['reason'] == 'source already has >=6 leading non-numeric lines',
                   'reason=%r' % rep['reason'])
            expect(rep['points'] == 9, 'points=%r, want 9' % rep['points'])
            a, b = open(src, 'rb').read(), open(out, 'rb').read()
            expect(a == b, 'file is not byte-identical (%d vs %d bytes)' % (len(a), len(b)))
            expect(rep['src_sha256'] == rep['out_sha256'], 'hashes differ on a verbatim copy')
            return 'added 0, OUT byte-identical to SRC (%d bytes)' % len(b)
        finally:
            pass

    def case3():
        # 3 header lines: pad exactly 3
        tmp = newdir('st3')
        try:
            src = os.path.join(tmp, 'hdr3.dat')
            out = os.path.join(tmp, 'hdr3_aligned.dat')
            head = 'COMM  a\nCOMM  b\n! third\n'
            open(src, 'wb').write(head.encode('utf-8') + _two_col(n=8))
            rep = run_make(src, out)
            expect(rep['added_lines'] == 3, 'added_lines=%r, want 3' % rep['added_lines'])
            expect(rep['leading_non_numeric'] == 3, 'leading=%r, want 3' % rep['leading_non_numeric'])
            expect(rep['points'] == 8, 'points=%r, want 8' % rep['points'])
            lines = open(out, 'rb').read().decode('utf-8').split('\n')
            expect(lines[0].startswith('COMM  generated by dsh-xrd dat_align'),
                   'line1=%r' % lines[0])
            expect(lines[2] == 'COMM  -', 'line3=%r' % lines[2])
            expect(lines[3:6] == ['COMM  a', 'COMM  b', '! third'],
                   'original header not preserved at lines 4-6: %r' % lines[3:6])
            expect(lines[6].startswith('3.000 '), 'first data line=%r' % lines[6])
            expect(run_check(out)['points_after_ins10'] == 8,
                   'points_after_ins10 != 8')
            return '3 original header lines + 3 added = 6, original text kept below'
        finally:
            pass

    def case4():
        # 3-column data (.fxye style) works
        tmp = newdir('st4')
        try:
            src = os.path.join(tmp, 'fxye3c.dat')
            out = os.path.join(tmp, 'fxye3c_aligned.dat')
            rows = ['%.2f %.1f 1.0' % (10.0 + i * 0.01, 50.0 + i) for i in range(7)]
            open(src, 'wb').write(('\n'.join(rows) + '\n').encode('utf-8'))
            rep = run_make(src, out)
            expect(rep['added_lines'] == 6, 'added_lines=%r' % rep['added_lines'])
            expect(rep['columns'] == 3, 'columns=%r, want 3' % rep['columns'])
            expect(rep['points'] == 7, 'points=%r, want 7' % rep['points'])
            expect(abs(rep['two_theta_min'] - 10.0) < 1e-9, '2theta_min=%r' % rep['two_theta_min'])
            expect(run_check(out)['columns'] == 3, 'check columns != 3')
            return '3 columns accepted, %d points, added 6' % rep['points']
        finally:
            pass

    def case5():
        # a bad row in the middle: SystemExit 1 naming the line
        tmp = newdir('st5')
        try:
            src = os.path.join(tmp, 'badmid.dat')
            out = os.path.join(tmp, 'badmid_aligned.dat')
            body = ('3.000 100\n3.020 101\n3.040 abc\n3.060 103\n'
                    '3.080 104\n3.100 105\n3.120 106\n3.140 107\n')
            open(src, 'wb').write(body.encode('utf-8'))
            code, msg = exit_code(lambda: run_make(src, out))
            expect(code == 1, 'exit code %r, want 1' % code)
            expect('line 3' in msg, 'message does not name line 3: %r' % msg)
            expect('column 2' in msg, 'message does not name column 2: %r' % msg)
            expect(not os.path.exists(out), 'a failed run left %s behind' % out)
            # a fourth column must be rejected too
            src4 = os.path.join(tmp, 'bad4c.dat')
            open(src4, 'wb').write(b'3.000 100 1 9\n3.020 101 1 9\n')
            code4, msg4 = exit_code(lambda: run_make(src4, os.path.join(tmp, 'o4.dat')))
            expect(code4 == 1 and 'line 1' in msg4, '4-column: code=%r msg=%r' % (code4, msg4))
            # non-finite tokens are not data either
            srcn = os.path.join(tmp, 'badnan.dat')
            open(srcn, 'wb').write(b'3.000 100\n3.020 nan\n')
            coden, msgn = exit_code(lambda: run_make(srcn, os.path.join(tmp, 'on.dat')))
            expect(coden == 1 and 'line 2' in msgn, 'nan: code=%r msg=%r' % (coden, msgn))
            return 'line 3 column 2 rejected (exit 1); 4-column and nan rows rejected too'
        finally:
            pass

    def case6():
        # idempotency: same SRC + same note -> byte-identical OUT, both paths
        tmp = newdir('st6')
        try:
            src = os.path.join(tmp, 'idem.dat')
            open(src, 'wb').write(_two_col(n=12) + b'')
            o1 = os.path.join(tmp, 'idem_a.dat')
            o2 = os.path.join(tmp, 'idem_b.dat')
            r1 = run_make(src, o1, note='same note')
            r2 = run_make(src, o2, note='same note')
            b1, b2 = open(o1, 'rb').read(), open(o2, 'rb').read()
            expect(b1 == b2, 'two runs differ (%d vs %d bytes)' % (len(b1), len(b2)))
            expect(r1['out_sha256'] == r2['out_sha256'], 'out hashes differ')
            # re-running ON THE OUTPUT adds nothing (this is the idempotency that
            # protects a padded file from being padded twice)
            o3 = os.path.join(tmp, 'idem_c.dat')
            r3 = run_make(o1, o3, note='same note')
            expect(r3['added_lines'] == 0, 're-align of a padded file added %r' % r3['added_lines'])
            expect(open(o3, 'rb').read() == b1, 're-align changed the bytes')
            # --force is required to overwrite, and then reproduces the bytes
            code, _ = exit_code(lambda: run_make(src, o1, note='same note'))
            expect(code == 2, 'existing OUT without --force gave exit %r, want 2' % code)
            r4 = run_make(src, o1, note='same note', force=True)
            expect(r4['out_sha256'] == r1['out_sha256'], '--force changed the bytes')
            expect(open(o1, 'rb').read() == b1, '--force changed the bytes')
            return 'two runs identical, re-align adds 0, --force reports exit 2 then reproduces'
        finally:
            pass

    try:
        case('1 no header, 2 cols -> +6 lines, all points kept', case1)
        case('2 6 header lines already -> +0, byte-identical copy', case2)
        case('3 3 header lines -> +3, original text preserved', case3)
        case('4 3-column data accepted', case4)
        case('5 bad data row -> SystemExit 1 naming line+column', case5)
        case('6 idempotency (repeat, re-align, --force)', case6)
    finally:
        # never leave scratch data behind, even when a case blows up
        for d in scratch_dirs:
            shutil.rmtree(d, ignore_errors=True)

    failed = 0
    for ok, name, detail in results:
        if not ok:
            failed += 1
        print('%s  %s%s' % ('PASS' if ok else 'FAIL', name,
                            ('  [%s]' % detail) if detail and ok else ''))
        if not ok:
            print('      %s' % detail)
    print('%d/%d cases passed' % (len(results) - failed, len(results)))
    return 1 if failed else 0


