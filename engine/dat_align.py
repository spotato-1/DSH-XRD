def build_parser():
    p = argparse.ArgumentParser(
        prog='dat_align.py',
        description='Prepend the six comment lines FullProf Ins=10 skips, so no '
                    'real data point is eaten.')
    p.add_argument('--selftest', action='store_true',
                   help='run the built-in self test and exit')
    sub = p.add_subparsers(dest='cmd')

    m = sub.add_parser('make', help='write an Ins=10-aligned copy of a data file')
    m.add_argument('--src', required=True)
    m.add_argument('--out', required=True)
    m.add_argument('--note', default=None,
                   help='text of the first COMM line (default: %r)' % DEFAULT_NOTE)
    m.add_argument('--force', action='store_true', help='overwrite an existing --out')
    m.add_argument('--json', action='store_true', help='print the report as JSON')

    c = sub.add_parser('check', help='report the Ins=10 status of a data file')
    c.add_argument('--dat', required=True)
    c.add_argument('--json', action='store_true', help='print the report as JSON')
    return p


def _emit(text, stream=None):
    """Write one line, never letting the console encoding crash the run.

    Every path and every note has already been through ascii_safe(), so there is
    normally nothing to encode; this is the belt-and-braces guard for a note the
    caller passed in and a stream whose codec cannot represent it (a GBK console
    raises UnicodeEncodeError and would turn a successful write into a crash).
    """
    stream = stream or sys.stdout
    data = text if text.endswith('\n') else text + '\n'
    try:
        stream.write(data)
        stream.flush()
    except (UnicodeEncodeError, LookupError):
        buf = getattr(stream, 'buffer', None)
        payload = data.encode('ascii', 'backslashreplace')
        if buf is not None:
            buf.write(payload)
            buf.flush()
        else:                                   # pragma: no cover
            stream.write(payload.decode('ascii'))


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        if args.selftest:
            return selftest()
        if args.cmd == 'make':
            rep = run_make(args.src, args.out, note=args.note, force=args.force)
            _emit(json.dumps(rep, indent=1, ensure_ascii=True) if args.json
                  else _text_make(rep))
            return 0
        if args.cmd == 'check':
            rep = run_check(args.dat)
            _emit(json.dumps(rep, indent=1, ensure_ascii=True) if args.json
                  else _text_check(rep))
            return 0
    except DatAlignError as e:
        _emit('dat_align: %s' % ascii_safe(e), sys.stderr)
        return e.code
    except OSError as e:
        _emit('dat_align: %s' % ascii_safe(e), sys.stderr)
        return 1
    build_parser().print_help()
    return 1


if __name__ == '__main__':
    sys.exit(main())