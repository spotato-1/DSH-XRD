def _fmt(v, spec='%s'):
    return 'n/a' if v is None else spec % v


def _text_make(rep):
    """Human-readable make report, as one string (the CLI writes it via _emit)."""
    return '\n'.join([
        'make: OK',
        '  src            %s' % rep['src'],
        '  out            %s' % rep['out'],
        '  added_lines    %d  (%s)' % (rep['added_lines'], rep['reason']),
        '  blank_lines    %d' % rep['blank_lines'],
        '  points         %d  (%s column(s))'
        % (rep['points'], _fmt(rep['columns'])),
        '  2theta         %s .. %s   step %s  constant=%s'
        % (_fmt(rep['two_theta_min'], '%.6f'), _fmt(rep['two_theta_max'], '%.6f'),
           _fmt(rep['step'], '%.6f'), rep['step_constant']),
        '  src_sha256     %s' % rep['src_sha256'],
        '  out_sha256     %s' % rep['out_sha256'],
    ])


def _text_check(rep):
    """Human-readable check report, as one string."""
    return '\n'.join([
        'check: %s' % rep['file'],
        '  bytes %d  encoding %s  line_ending %s  lines %d'
        % (rep['bytes'], rep['encoding'], rep['line_ending'], rep['total_lines']),
        '  leading non-numeric lines %d  (blank %d)'
        % (rep['leading_non_numeric'], rep['blank_lines']),
        '  points %d  columns %s' % (rep['points'], _fmt(rep['columns'])),
        '  2theta %s .. %s  step %s'
        % (_fmt(rep['two_theta_min'], '%.6f'), _fmt(rep['two_theta_max'], '%.6f'),
           _fmt(rep['step'], '%.6f')),
        '  step constant %s  (max drift %s vs tol %g)'
        % (rep['step_constant'], _fmt(rep['step_drift'], '%.3e'),
           rep['step_tolerance']),
        '  Ins=10 ready %s  (needs %d leading lines, has %d)'
        % (rep['ins10_ok'], rep['ins10_required'], rep['leading_non_numeric']),
        '  points after Ins=10 %d  (lost %d)'
        % (rep['points_after_ins10'], rep['points_lost_by_ins10']),
        '  advice: %s' % rep['advice'],
    ])


def print_make(rep):
    """Backwards-compatible printer (the CLI itself goes through _emit)."""
    _emit(_text_make(rep))


def print_check(rep):
    _emit(_text_check(rep))


