def run_check(path):
    """Describe what FullProf Ins=10 would do with this file. Writes nothing."""
    if not os.path.isfile(path):
        raise DatAlignError('file not found: %s' % ascii_safe(path))
    lines, meta = read_lines(path)
    try:
        n0, blank, rows, columns = analyse(lines)
    except DatAlignError as e:
        raise DatAlignError('%s [%s]' % (e, ascii_safe(path)))
    stats = report_stats(rows, columns)
    total = len(lines)
    # What survives Ins=10 = every parsed data row, PROVIDED the header it now
    # carries is at least six lines long. Counting "total_lines - n0 - 6" would
    # be wrong for a file that has comment lines in the middle of the data (they
    # are skipped by every reader, so they cost no points) - the parsed row
    # count is the quantity that matters, and for the files this module writes
    # the two are identical.
    surv = stats['points'] if n0 >= SKIP_INS10 else 0
    rep = {
        'ok': True,
        'file': ascii_safe(os.path.abspath(path)),
        'bytes': meta['bytes'],
        'encoding': meta['encoding'],
        'line_ending': meta['line_ending'],
        'total_lines': total,
        'leading_non_numeric': n0,
        'blank_lines': blank,
        'points': stats['points'],
        'columns': columns,
        'two_theta_min': stats['two_theta_min'],
        'two_theta_max': stats['two_theta_max'],
        'step': stats['step'],
        'step_constant': stats['step_constant'],
        'step_drift': stats['step_drift'],
        'step_tolerance': STEP_TOL,
        'ins10_required': SKIP_INS10,
        'ins10_ok': n0 >= SKIP_INS10,
        'points_lost_by_ins10': 0 if n0 >= SKIP_INS10 else max(0, SKIP_INS10 - n0),
        'points_after_ins10': surv,
        'sha256': sha256_file(path),
    }
    if n0 >= SKIP_INS10:
        rep['advice'] = 'ok for Ins=10: %d leading non-numeric line(s)' % n0
    else:
        rep['advice'] = ('Ins=10 would eat %d real data point(s) and shift the start '
                         'angle; run: dat_align.py make --src <this> --out <copy>'
                         % max(0, SKIP_INS10 - n0))
    return rep


