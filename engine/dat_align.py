#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""FullProf Ins=10 header alignment for two/three-column powder data.

WHY (measured, do not re-litigate the premise): FullProf's Ins=10 SKIPS the
first SIX lines of the data file, unconditionally, because it assumes a comment
header is there. Our two-column .dat files have no such header, so fp2k eats the
first six REAL data points as "comments": a 7351-line Y2O3.dat is read back as
7345 points and the start angle moves from 3.000 to 3.120 while the end angle
stays put. Nothing about the refinement is wrong - the file was.

So this module does ONE thing: it manufactures the header Ins=10 wants.

    make   prepend just enough COMM lines that the leading non-numeric count is
           exactly 6, then hand back a byte-identical copy of the source lines.
           When the source already has >= 6 leading non-numeric lines nothing is
           added at all and the bytes are copied verbatim (a file that already
           works must not be perturbed - its other consumer may care).
    check  report what FullProf would do with a file: how many lines it would
           eat, how many points survive, and whether the 2theta grid is really
           uniform. Read-only, writes nothing.

Design constraints worth knowing before editing:

  * There is NO local pruning. A data file must NEVER lose points: n0 counts
    from the top only, so the first six surviving data points are the very ones
    Ins=10 would have discarded, and they are part of the contract.
  * A 2- or 3-column data row must be ALL finite floats. The parser is STRICTER
    than data_io._is_data_row on purpose: that one only inspects the first two
    tokens, which would accept `3.000 4.0 garbage`; here a bad third column is
    a hard error naming the line and the column. That strictness is also what
    makes idempotency provable - every padded file starts with six lines that
    are non-numeric by construction, so re-running it adds nothing.
  * Counting stops at the first data row. Hook-shaped rules ("a comment line
    between data rows is skipped") cannot be idempotent: the copy would be
    re-padded every time it was fed back in.
  * The comment markers are 'COMM', '#' and '!'. 'COMM' is FullProf's own and
    it is the one that matters, because make() writes it: a reader that did not
    recognise 'COMM' could not read back the file this module produces (and the
    note on line 1 would be rejected as a seven-column data row).
  * Output is ASCII only, failures raise SystemExit with a non-zero code, and
    the report is a plain dict so it can be printed as JSON for the JS layer.
    That ASCII rule covers PATHS as well (ascii_safe escapes them), because a
    Chinese data-file name reaches stdout through the report and a GBK console
    would otherwise raise UnicodeEncodeError inside a successful write.

CLI:
    python dat_align.py make  --src SRC.dat --out OUT.dat [--note TEXT] [--force]
    python dat_align.py check --dat D.dat [--json]
    python dat_align.py --selftest
"""

import argparse
import hashlib
import json
import math
import os
import shutil
import sys
import tempfile

# FullProf Ins=10 skips exactly this many leading lines.
SKIP_INS10 = 6
# Report/manifest step tolerance for "is the grid constant".
STEP_TOL = 1e-6
# Rows carrying more than this many numeric columns are not 2theta/intensity data.
MAX_COLUMNS = 3
# Lines FullProf itself treats as comments. 'COMM' is THE prefix that matters:
# it is what make() writes, so the reader has to recognise it or the file this
# module produces could not be read back by this module (and, worse, a padded
# COMM line full of our own words would be rejected as a 7-column data row).
COMMENT_PREFIX = ('#', '!', 'COMM')
COMM_LINE = 'COMM  -'
DEFAULT_NOTE = 'generated by dsh-xrd dat_align for Ins=10'


class DatAlignError(Exception):
    """A rejected operation. Carries `code`, which becomes the SystemExit code."""

    def __init__(self, message, code=1):
        Exception.__init__(self, message)
        self.code = code


# ---------------------------------------------------------------------------
# reading
# ---------------------------------------------------------------------------
def _decode(blob):
    """Bytes -> text, reporting the encoding. UTF-8 BOM is stripped, not kept."""
    if blob.startswith(b'\xef\xbb\xbf'):
        return blob[3:].decode('utf-8', errors='replace'), 'utf-8 (BOM stripped)'
    try:
        return blob.decode('utf-8'), 'utf-8'
    except UnicodeDecodeError:
        # A vendor header may carry cp932/latin-1 bytes. The DATA lines are what
        # gets validated, so a lossy header decode is tolerable here.
        return blob.decode('utf-8', errors='replace'), 'non-utf-8 (errors=replace)'


def read_lines(path):
    """(lines, meta). Line endings normalised to LF, final newline dropped."""
    try:
        with open(path, 'rb') as fh:
            blob = fh.read()
    except OSError as e:
        raise DatAlignError('cannot read %s: %s' % (ascii_safe(path), ascii_safe(e)))
    text, encoding = _decode(blob)
    crlf = '\r\n' in text
    text = text.replace('\r\n', '\n').replace('\r', '\n')
    lines = text.split('\n')
    if lines and lines[-1] == '':
        lines = lines[:-1]
    return lines, {'bytes': len(blob), 'encoding': encoding,
                   'line_ending': 'CRLF' if crlf else 'LF', 'text': text}


def sha256_bytes(blob):
    return hashlib.sha256(blob).hexdigest()


def sha256_file(path):
    try:
        with open(path, 'rb') as fh:
            return sha256_bytes(fh.read())
    except OSError as e:
        raise DatAlignError('cannot read %s: %s' % (ascii_safe(path), ascii_safe(e)))


# ---------------------------------------------------------------------------
# rows
# ---------------------------------------------------------------------------
def tokens(line):
    return line.strip().replace(',', ' ').split()


def is_comment(line):
    s = line.strip()
    return bool(s) and s.startswith(COMMENT_PREFIX)


def parse_data_row(line, number):
    """[(x, y, ...)] for a data row, [] when the row is not numeric.

    Returns [] for a comment line and for a blank line (both are ordinary
    non-numeric lines for the leading-count rule). ANY other row must carry
    MAX_COLUMNS or fewer tokens and every one of them must be a finite float -
    otherwise this raises with the exact line and column, because a data file
    with a mangled row silently shifts every reflection.
    """
    if not tokens(line):
        return []
    if is_comment(line):
        return []
    toks = tokens(line)
    if len(toks) > MAX_COLUMNS:
        raise DatAlignError('line %d: %d columns found, expected 2 or 3: %r'
                            % (number, len(toks), line.strip()[:120]))
    values = []
    for col, tok in enumerate(toks, 1):
        try:
            val = float(tok)
        except ValueError:
            raise DatAlignError('line %d column %d: %r is not a finite number: %r'
                                % (number, col, tok, line.strip()[:120]))
        if not math.isfinite(val):
            raise DatAlignError('line %d column %d: %r is not a finite number: %r'
                                % (number, col, tok, line.strip()[:120]))
        values.append(val)
    return values


def analyse(lines):
    """Split into (leading non-numeric count, blank count, rows, columns).

    The leading count STOPS at the first data row - that is what makes `make`
    idempotent (see module docstring). Rows keeps the 1-based line number so an
    error can name the line in the ORIGINAL file.
    """
    n0 = blank = 0
    rows = []
    columns = None
    in_data = False
    for i, line in enumerate(lines):
        num = i + 1
        values = parse_data_row(line, num)
        if not values:
            if not in_data:
                n0 += 1
                if not tokens(line):
                    blank += 1
            continue
        in_data = True
        if columns is None:
            columns = len(values)
        elif len(values) != columns:
            raise DatAlignError('line %d: %d column(s) here but %d column(s) in the '
                                'first data row %r'
                                % (num, len(values), columns, line.strip()[:120]))
        rows.append((num, values))
    return n0, blank, rows, columns


def report_stats(rows, columns):
    """points / 2theta range / constant-step test for the parsed rows."""
    stats = {'points': len(rows), 'columns': columns,
             'two_theta_min': None, 'two_theta_max': None, 'step': None,
             'step_constant': None, 'step_drift': None, 'step_tolerance': STEP_TOL}
    if not rows:
        return stats
    xs = [r[1][0] for r in rows]
    stats['two_theta_min'] = xs[0]
    stats['two_theta_max'] = xs[-1]
    if len(xs) < 2:
        return stats
    diffs = [b - a for a, b in zip(xs, xs[1:])]
    step = sum(diffs) / len(diffs)
    stats['step'] = step
    drift = max(abs(d - step) for d in diffs)
    stats['step_drift'] = drift
    stats['step_constant'] = drift <= STEP_TOL
    return stats


# ---------------------------------------------------------------------------
# make
# ---------------------------------------------------------------------------
def build_header(n_add, note, src_name, src_sha, n0):
    """The lines to prepend. Fixed shape, no timestamps: idempotency needs it.

    Line 1 carries the note, line 2 the source name + short hash, the rest are
    bare 'COMM  -'. Only the deficiency (6 - n0) is written, so a source that
    already had 3 header lines gets 3 more, not 6.
    """
    note = ' '.join(str(note).split()) if note else DEFAULT_NOTE
    head = ['COMM  %s' % note,
            'COMM  source %s sha256 %s' % (src_name, src_sha[:12])]
    while len(head) < n_add:
        head.append(COMM_LINE)
    return head[:n_add]


def ascii_safe(text):
    """Backslash-escape everything outside printable ASCII.

    The contract is that no output line leaves this module as raw non-ASCII, and
    that includes a PATH: a Chinese project directory or data file name reaches
    stdout through the report and the error messages. Escaping keeps the byte
    stream valid in a GBK console while still naming the real file. The content
    of the source FILE is never touched by this - only what is printed.
    """
    s = str(text)
    out = []
    for ch in s:
        if 32 <= ord(ch) < 127:
            out.append(ch)
        elif ch == '\t':
            out.append('\\t')
        else:
            out.append('\\u%04x' % ord(ch) if ord(ch) <= 0xffff else '\\U%08x' % ord(ch))
    return ''.join(out)


def run_make(src, out, note=None, force=False):
    """Write the Ins=10-aligned copy. Returns the report dict."""
    if not os.path.isfile(src):
        raise DatAlignError('source not found: %s' % ascii_safe(src))
    if os.path.exists(out):
        if not force:
            raise DatAlignError('output already exists: %s (pass --force to overwrite)'
                                % ascii_safe(out), code=2)
        if os.path.isdir(out):
            raise DatAlignError('output path is a directory: %s' % ascii_safe(out))
        try:
            if os.path.samefile(src, out):
                raise DatAlignError('--src and --out are the same file, refusing to '
                                    'overwrite the source: %s' % ascii_safe(src))
        except OSError:
            pass
    elif os.path.normcase(os.path.abspath(src)) == os.path.normcase(os.path.abspath(out)):
        raise DatAlignError('--src and --out are the same file: %s' % ascii_safe(src))

    src_sha = sha256_file(src)
    lines, meta = read_lines(src)
    try:
        n0, blank, rows, columns = analyse(lines)
    except DatAlignError as e:
        raise DatAlignError('%s [%s]' % (e, ascii_safe(src)))

    out_dir = os.path.dirname(os.path.abspath(out)) or '.'
    if not os.path.isdir(out_dir):
        raise DatAlignError('output directory does not exist: %s' % ascii_safe(out_dir))

    # Path A: the file already has what Ins=10 needs - verbatim byte copy.
    if n0 >= SKIP_INS10:
        raw = open(src, 'rb').read()
        write_atomic(out, raw)
        added = 0
        reason = 'source already has >=6 leading non-numeric lines'
        out_sha = sha256_bytes(raw)
    else:
        # Path B: prepend the deficiency, keep every source line untouched.
        added = SKIP_INS10 - n0
        head = build_header(added, note, ascii_safe(os.path.basename(src)), src_sha, n0)
        text = '\n'.join(head + lines) + '\n'
        raw = text.encode('utf-8')
        write_atomic(out, raw)
        reason = 'prepended %d COMM line(s) so Ins=10 skips only the header' % added
        out_sha = sha256_bytes(raw)

    stats = report_stats(rows, columns)
    rep = {
        'ok': True,
        'src': ascii_safe(os.path.abspath(src)),
        'out': ascii_safe(os.path.abspath(out)),
        'added_lines': added,
        'blank_lines': blank,
        'points': stats['points'],
        'two_theta_min': stats['two_theta_min'],
        'step': stats['step'],
        'two_theta_max': stats['two_theta_max'],
        'columns': stats['columns'],
        'src_sha256': src_sha,
        'out_sha256': out_sha,
        # extras (not required by the contract, but the caller needs them to
        # tell why nothing was padded, and what FullProf will see after padding)
        'leading_non_numeric': n0,
        'ins10_ok': (n0 + added) >= SKIP_INS10,
        'points_after_ins10': stats['points'] if (n0 + added) >= SKIP_INS10 else 0,
        'step_constant': stats['step_constant'],
        'step_drift': stats['step_drift'],
        'step_tolerance': STEP_TOL,
        'line_ending_in': meta['line_ending'],
        'encoding_in': meta['encoding'],
        'out_line_ending': 'LF',
        'reason': reason,
    }
    return rep


def write_atomic(path, blob):
    """Write bytes to path via a same-directory temp file, then os.replace.

    A killed run leaves either the old file or the complete new one, never a
    truncated .dat that fp2k would happily half-read.
    """
    tmp = os.path.join(os.path.dirname(os.path.abspath(path)) or '.',
                       '.%s.tmp-%d' % (os.path.basename(path), os.getpid()))
    try:
        with open(tmp, 'wb') as fh:
            fh.write(blob)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except Exception:
        try:
            if os.path.exists(tmp):
                os.remove(tmp)
        except OSError:
            pass
        raise


